// Regenerates verify/old-runner.js by extracting the session-01 main-thread
// runner verbatim from the commit that introduced it. Pinned to that commit so
// the equivalence proof keeps comparing against the runner actually replaced,
// not against whatever HEAD happens to hold.
//
//   node verify/make-old-runner.js
const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const SESSION_01 = "73d7f69";   // "Session 1: predict/run/compare loop, schema, debug panel"

const old = execFileSync("git", ["show", `${SESSION_01}:index.html`], {
  cwd: path.resolve(__dirname, ".."), encoding: "utf8"
});

const start = "  function formatArg(a) {";
const end = '    return { output: lines.join("\\n"), threw: threw ? String(threw) : null, lineCount: lines.length };\n  }\n';
const i = old.indexOf(start);
const j = old.indexOf(end);
if (i < 0 || j < 0) throw new Error("could not find the session-01 runner in " + SESSION_01);

const body = old.slice(i, j + end.length).replace("function runSource(source)", "function OLD_runSource(source)");

fs.writeFileSync(path.join(__dirname, "old-runner.js"),
  `// GENERATED by verify/make-old-runner.js from commit ${SESSION_01}. Do not edit.\n` +
  "// The session-01 main-thread runner, kept only to prove the worker runner\n" +
  "// produces byte-identical output to the one it replaced.\n" +
  "(function () {\n" + body + "\n  window.OLD_runSource = OLD_runSource;\n})();\n");

console.log("wrote verify/old-runner.js from " + SESSION_01);
